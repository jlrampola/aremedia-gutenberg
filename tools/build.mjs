import { createHash } from 'node:crypto';
import { copyFileSync, cpSync, mkdirSync, readFileSync, watch, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath( new URL( '..', import.meta.url ) );

function build() {
	const metadata = JSON.parse( readFileSync( `${ root }/src/block.json`, 'utf8' ) );
	const source = readFileSync( `${ root }/src/index.js`, 'utf8' );
	const script = `/* Generated by npm run build. */\n( function( wp, metadata ) {\n${ source }\n} )( window.wp, ${ JSON.stringify( metadata ) } );\n`;
	const version = createHash( 'sha256' ).update( script ).update( readFileSync( `${ root }/src/style.css` ) ).digest( 'hex' ).slice( 0, 16 );
	mkdirSync( `${ root }/build`, { recursive: true } );
	for ( const file of [ 'block.json', 'render.php', 'style.css' ] ) {
		copyFileSync( `${ root }/src/${ file }`, `${ root }/build/${ file }` );
	}
	cpSync( `${ root }/src/fonts`, `${ root }/build/fonts`, { recursive: true } );
	cpSync( `${ root }/src/assets`, `${ root }/build/assets`, { recursive: true } );
	writeFileSync( `${ root }/build/index.js`, script );
	writeFileSync( `${ root }/build/index.asset.php`, `<?php\n/** Generated editor dependencies. */\nreturn array( 'dependencies' => array( 'wp-blocks', 'wp-block-editor', 'wp-components', 'wp-element', 'wp-data', 'wp-core-data', 'wp-i18n', 'wp-html-entities' ), 'version' => '${ version }' );\n` );
	console.log( `Built Category Articles (${ version }).` );
}

build();
if ( process.argv.includes( '--watch' ) ) {
	let timer;
	watch( `${ root }/src`, { recursive: true }, () => {
		clearTimeout( timer );
		timer = setTimeout( () => {
			try {
				build();
			} catch ( error ) {
				console.error( error.message );
			}
		}, 100 );
	} );
	console.log( 'Watching src/; press Ctrl+C to stop.' );
}
